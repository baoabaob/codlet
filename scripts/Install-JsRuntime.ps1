[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Destination,
    [ValidateSet('win-x64', 'win-arm64')][string]$Platform,
    [string]$ArchivePath
)
$ErrorActionPreference = 'Stop'
if (-not $Platform) {
    $architecture = [System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString()
    $Platform = switch ($architecture) {
        'X64' { 'win-x64' }
        'Arm64' { 'win-arm64' }
        default { throw "Unsupported Windows architecture: $architecture" }
    }
}
$lockPath = Join-Path $PSScriptRoot '../runtime/node-runtime.json'
$lock = [System.IO.File]::ReadAllText($lockPath) | ConvertFrom-Json
$platformSpec = $lock.platforms.$Platform
$root = [System.IO.Path]::GetFullPath($Destination)
function Assert-PlainPath([string]$Path) {
    for ($part = [System.IO.Path]::GetFullPath($Path); $part; $part = [System.IO.Path]::GetDirectoryName($part)) {
        if ((Test-Path -LiteralPath $part) -and (([System.IO.File]::GetAttributes($part) -band [System.IO.FileAttributes]::ReparsePoint) -ne 0)) {
            throw "Linked runtime paths are not accepted: $part"
        }
    }
}
Assert-PlainPath $root
$runtimeDirectory = Join-Path $root ("runtime/node-v{0}-{1}" -f $lock.version, $Platform)
$nodePath = Join-Path $runtimeDirectory 'node.exe'
$licensePath = Join-Path $runtimeDirectory 'LICENSE'
Assert-PlainPath $runtimeDirectory
if (Test-Path -LiteralPath $runtimeDirectory) {
    Assert-PlainPath $nodePath
    Assert-PlainPath $licensePath
    if ((Test-Path -LiteralPath $nodePath -PathType Leaf) -and (Test-Path -LiteralPath $licensePath -PathType Leaf) -and
        ((Get-FileHash -LiteralPath $nodePath -Algorithm SHA256).Hash -ieq $platformSpec.executableSha256) -and
        ((Get-FileHash -LiteralPath $licensePath -Algorithm SHA256).Hash -ieq $platformSpec.licenseSha256)) {
        Write-Output "JS runtime ready: $nodePath"
        return
    }
    throw "The managed runtime is incomplete or has a different hash: $runtimeDirectory. Repair this version directory before staging again."
}
$runtimeParent = [System.IO.Path]::GetDirectoryName($runtimeDirectory)
[System.IO.Directory]::CreateDirectory($runtimeParent) | Out-Null
$temporaryDirectory = Join-Path $runtimeParent ('.node-runtime-' + [Guid]::NewGuid().ToString('N') + '.tmp')
[System.IO.Directory]::CreateDirectory($temporaryDirectory) | Out-Null
$temporaryArchive = $null
$temporaryNode = Join-Path $temporaryDirectory 'node.exe'
$temporaryLicense = Join-Path $temporaryDirectory 'LICENSE'
try {
    if (-not $ArchivePath) {
        $temporaryArchive = Join-Path $temporaryDirectory 'download.zip'
        $ArchivePath = $temporaryArchive
        $url = $lock.baseUrl + '/' + $platformSpec.archive
        # curl is bundled with supported Windows versions. No shell fragments,
        # install hooks, package manager, PATH edits or plugin execution occur.
        & curl.exe --fail --silent --show-error --location --connect-timeout 15 --max-time 180 --output $ArchivePath $url
        if ($LASTEXITCODE -ne 0) { throw "Node download failed with curl exit $LASTEXITCODE" }
    }
    $ArchivePath = [System.IO.Path]::GetFullPath($ArchivePath)
    if ((Get-FileHash -LiteralPath $ArchivePath -Algorithm SHA256).Hash -ine $platformSpec.archiveSha256) {
        throw 'Node archive hash differs from the checked-in runtime pin.'
    }
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    $archive = [System.IO.Compression.ZipFile]::OpenRead($ArchivePath)
    try {
        $prefix = 'node-v' + $lock.version + '-' + $Platform + '/'
        foreach ($item in @(@('node.exe', $temporaryNode), @('LICENSE', $temporaryLicense))) {
            $entry = $archive.GetEntry($prefix + $item[0])
            if (-not $entry) { throw ('Missing official archive member: ' + $item[0]) }
            $inputStream = $entry.Open()
            $outputStream = [System.IO.File]::Open($item[1], [System.IO.FileMode]::CreateNew)
            try { $inputStream.CopyTo($outputStream) } finally { $outputStream.Dispose(); $inputStream.Dispose() }
        }
    } finally { $archive.Dispose() }
    if ((Get-FileHash -LiteralPath $temporaryNode -Algorithm SHA256).Hash -ine $platformSpec.executableSha256) {
        throw 'Node executable hash differs from the checked-in runtime pin.'
    }
    if ((Get-FileHash -LiteralPath $temporaryLicense -Algorithm SHA256).Hash -ine $platformSpec.licenseSha256) {
        throw 'Node license hash differs from the checked-in runtime pin.'
    }
    if ($temporaryArchive) { Remove-Item -LiteralPath $temporaryArchive; $temporaryArchive = $null }
    Assert-PlainPath $runtimeDirectory
    [System.IO.Directory]::Move($temporaryDirectory, $runtimeDirectory)
    Write-Output "JS runtime staged: $nodePath"
} finally {
    # Delete only the three exact temporary files generated by this invocation.
    foreach ($temporary in @($temporaryArchive, $temporaryNode, $temporaryLicense)) {
        if ($temporary -and (Test-Path -LiteralPath $temporary -PathType Leaf)) {
            Assert-PlainPath $temporary
            Remove-Item -LiteralPath $temporary
        }
    }
    if (Test-Path -LiteralPath $temporaryDirectory) {
        Assert-PlainPath $temporaryDirectory
        [System.IO.Directory]::Delete($temporaryDirectory, $false)
    }
}
