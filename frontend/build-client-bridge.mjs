import {build} from 'esbuild';
import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
export async function buildClientBridge(root) {
  const result=await build({absWorkingDir:root,entryPoints:['runtime/client-bridge.cjs'],bundle:true,
    write:false,format:'cjs',platform:'node',target:'node24',nodePaths:[resolve(root,'frontend/node_modules')]});
  const licenses=await Promise.all([['Acorn','acorn/LICENSE'],['eslint-scope','eslint-scope/LICENSE'],['esrecurse','esrecurse/esrecurse.js'],['estraverse','estraverse/LICENSE.BSD']].map(async([name,file])=>{
    const text=await readFile(resolve(root,'frontend/node_modules',file),'utf8');
    return name+'\n'+(name==='esrecurse'?text.match(/^\/\*[\s\S]*?\*\//)[0]:text);
  }));
  return '// Generated by frontend/build.mjs; generic owned-client transport.\n'+result.outputFiles[0].text
    +'\n/*\n'+licenses.join('\n\n').replaceAll('*/','* /')+'\n*/\n';
}
